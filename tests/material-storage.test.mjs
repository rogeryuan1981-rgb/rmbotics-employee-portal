import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createDatabase,seed,asUser,rpc} from '../scripts/local-db.mjs';
const db=await createDatabase();await seed(db);
const setup=await readFile(new URL('../supabase/migrations/20261116094447_training_material_storage.sql',import.meta.url),'utf8');
await db.exec(setup);await db.exec(setup);
await db.exec('alter table storage.objects enable row level security; grant usage on schema storage to authenticated; grant select,insert,update,delete on storage.objects to authenticated;');
const uid=i=>'20000000-0000-0000-0000-'+String(i).padStart(12,'0');
const eid=i=>'30000000-0000-0000-0000-'+String(i).padStart(12,'0');
const sessions={};for(let i=1;i<=5;i++)sessions[i]=(await db.query('insert into auth.sessions(user_id) values($1) returning id',[uid(i)])).rows[0].id;
const user=(i,fn)=>asUser(db,uid(i),sessions[i],fn);
const call=(i,a,p)=>rpc(db,uid(i),sessions[i],a,p);
const path='12345678-1234-1234-1234-123456789012/12345678-1234-1234-1234-123456789013.pdf';
const draftPath=path.replace('9013.pdf','9014.pdf');
test('private PDF files can only be uploaded by a training administrator',async()=>{
  await user(1,tx=>tx.query("insert into storage.objects(bucket_id,name) values('training-materials',$1)",[path]));
  await assert.rejects(user(2,tx=>tx.query("insert into storage.objects(bucket_id,name) values('training-materials',$1)",[draftPath])),/row-level security/);
  assert.equal((await db.query("select public from storage.buckets where id='training-materials'")).rows[0].public,false);
});
test('assigned learners can read their published PDF and cannot read draft or unrelated files',async()=>{
  const mid=path.split('/')[0];
  const content={title:'PDF課程',seconds:60,pass_score:80,question_count:1,minutes:0,cycle:'once',departments:[],start:'',end:'',materials:[{id:mid,title:'PDF',kind:'pdf',content:'https://example.supabase.co/storage/v1/object/authenticated/training-materials/'+path}],questions:[{id:'q1',kind:'single',prompt:'測試',options:['是','否'],correct:[0],explanation:'測試',material_id:mid}]};
  const course=await call(1,'course_save',{content});await call(1,'course_publish',{id:course.id,summary:'發布PDF'});
  const requirement=await call(1,'assign',{employee_id:eid(2),course_id:course.id,deadline:{mode:'assigned',days:30,makeup_days:30},key:'pdf-file-test'});
  await user(1,tx=>tx.query("insert into storage.objects(bucket_id,name) values('training-materials',$1)",[draftPath]));
  const readable=i=>user(i,tx=>tx.query("select name from storage.objects where bucket_id='training-materials'"));
  assert.deepEqual((await readable(2)).rows.map(x=>x.name),[path]);
  assert.equal((await readable(5)).rows.length,0);
  assert.equal((await readable(3)).rows.length,0);
  const changed=await user(1,tx=>tx.query("update storage.objects set name=$1 where bucket_id='training-materials' and name=$2 returning name",[draftPath+'x',path]));assert.equal(changed.rows.length,0);
  await db.query("update training.requirements set lifecycle='cancelled' where id=$1",[requirement.id]);assert.equal((await readable(2)).rows.length,0);
  const external=(await db.query("insert into training.external_courses(title,provider,created_by) values('外訓','測試',$1) returning id",[eid(1)])).rows[0].id;
  const enrollment=(await db.query('insert into training.external_enrollments(course_id,employee_id) values($1,$2) returning id',[external,eid(2)])).rows[0].id;
  const certificate=`${eid(2)}/${enrollment}/certificate.pdf`;
  await user(2,tx=>tx.query("insert into storage.objects(bucket_id,name) values('training-certificates',$1)",[certificate]));
  await db.query('update training.external_enrollments set certificate_path=$1 where id=$2',[certificate,enrollment]);
  assert.equal((await user(3,tx=>tx.query("select name from storage.objects where bucket_id='training-certificates'"))).rows.length,1);
  assert.equal((await user(5,tx=>tx.query("select name from storage.objects where bucket_id='training-certificates'"))).rows.length,0);
  await db.query("update public.employees set active=false,inactive_reason='測試停用' where id=$1",[eid(1)]);
  await assert.rejects(readable(1),/停用|失效/);
});
test.after(()=>db.close());
